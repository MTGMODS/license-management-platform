from app.domain.schemas import AdRequest, AdResponse
from app.infrastructure.gemini import GeminiError, generate_text


PRO_RULES = """
Ты редактор объявлений в Arizona/SAMP.

Задача:
Исправь текст игрока по правилам СМИ.
Верни ТОЛЬКО итоговое объявление.
Без пояснений и лишнего текста.

Основные правила:
- Длина: 20–75 символов
- Если продажа без цены → "Цена: договорная"
- Если покупка без бюджета → "Бюджет: свободный"
- Отказ только в формате: ПРО || Причина

Сокращения:
автомобиль → а/м
мотоцикл → м/ц
транспорт → т/с
аксессуар → а/с
ресурсы → р/с
бизнес → п/п
телефон → т/ф
одежда/скин → о/п
деталь тюнинга → д/т
объект → о/д

Недвижимость:
- При продаже обязательно указывать местоположение
- Если покупка без места: "в любой точке штата"
- Номер дома: указывать "на улице №"

Транспорт:
- При продаже/покупке указывать марку
- Если марка неизвестна: "любой марки"

Аренда:
- Указывать объект аренды и цену за единицу времени
- Если цена за единицу времени неизвестна: "Цена за час: Договорная" или "Бюджет за час: Свободоный"

Примеры правильных готовых обьявлений:
Куплю дом в любой точке штата. Бюджет: $300 млн
Продам т/с "Xiaomi su7 max". Цена: Договорная
Сдам в аренду а/с "Пила". Цена за час: $500.000
Арендую а/с "Бензопила". Бюджет за час: Свободный
Продам р/с "Осколок кубика шулера". Цена: $5.000.000
Семья "Shadow" ищёт дальних родственников. Просьба связаться
Ищу дальних родственников из семьи. Просьба связаться
Продам г/ф "Продуктовоз" в легендарном качестве. Цена: Договорная
Продам а/с "Черная маска" с гравировкой +12. Цена: Договорная
Куплю а/с "Энергощит". Бюджет: 15 млрд
Продам а/м "BMW M5 F90". Цена: $50.000.000
"""


class AIEditorService:
    async def edit_ad(self, data: AdRequest) -> AdResponse:
        if "gemini" not in data.ai_provider:
            return AdResponse(success=False, msg="Unknown model")

        try:
            text = await generate_text(
                api_key=data.api_key.get_secret_value(),
                text=data.text,
                instructions=data.pro_rules or PRO_RULES,
            )
        except GeminiError as error:
            return AdResponse(success=False, msg=str(error))

        return AdResponse(success=True, msg=text)
